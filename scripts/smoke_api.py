"""Exercise the persisted demo journey through a running LINEPILOT API.

Run after starting the API and seeding Northline:
    python scripts/smoke_api.py --base http://localhost:8000

The script creates schedules, a scenario, a simulation, and a report in the
configured local database. It fails on a broken workflow rather than printing
optimistic sample values.
"""

from __future__ import annotations

import argparse
import json
import time
from datetime import datetime, timedelta, timezone
from urllib.error import HTTPError
from urllib.request import Request, urlopen


def request(base: str, method: str, path: str, body: dict | None = None) -> dict:
    payload = None if body is None else json.dumps(body).encode("utf-8")
    req = Request(
        base.rstrip("/") + path,
        data=payload,
        method=method,
        headers={"Content-Type": "application/json", "Accept": "application/json"},
    )
    try:
        with urlopen(req, timeout=30) as response:
            data = response.read()
    except HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"{method} {path}: HTTP {exc.code}: {detail}") from exc
    return json.loads(data) if data else {}


def wait_for_run(base: str, resource: str, run_id: str, timeout: float) -> dict:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        run = request(base, "GET", f"/api/v1/{resource}/{run_id}")
        status = str(run.get("status", "")).lower()
        if status in {"completed", "failed", "cancelled", "canceled"}:
            if status != "completed":
                raise RuntimeError(f"{resource} {run_id} ended as {status}: {run.get('diagnostics')}")
            return run
        time.sleep(0.25)
    raise TimeoutError(f"{resource} {run_id} did not finish within {timeout:.0f} s")


def schedule(base: str, facility_id: str, algorithm: str, timeout: float, **extra: object) -> dict:
    posted = request(
        base,
        "POST",
        "/api/v1/schedules",
        {"facility_id": facility_id, "algorithm": algorithm, "objective": "makespan", **extra},
    )
    assert posted.get("id"), f"Schedule POST returned no id: {posted}"
    run = wait_for_run(base, "schedules", posted["id"], timeout)
    assert run.get("assignments"), f"{algorithm} schedule has no assignments"
    assert run.get("solver_status") in {"OPTIMAL", "FEASIBLE", "DISPATCHED", "optimal", "feasible", "dispatched"}, run
    return run


def as_utc(value: str) -> datetime:
    return datetime.fromisoformat(value.replace("Z", "+00:00")).astimezone(timezone.utc)


def metric_summary(run: dict) -> dict:
    metrics = run.get("metrics") or {}
    return {
        key: metrics.get(key)
        for key in (
            "makespan_minutes",
            "total_tardiness_minutes",
            "on_time_delivery_rate",
            "mean_job_waiting_minutes",
            "completed_jobs",
        )
        if key in metrics
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base", default="http://localhost:8000")
    parser.add_argument("--timeout", type=float, default=120)
    args = parser.parse_args()
    base = args.base

    boot = request(base, "GET", "/api/v1/bootstrap")
    facility = boot.get("facility") or {}
    machines = boot.get("machines") or []
    jobs = boot.get("jobs") or []
    assert facility.get("id") and len(machines) >= 6 and len(jobs) >= 20, "Northline demo is not seeded"
    print(f"Demo: {facility.get('name') or facility.get('facility_name')} — {len(jobs)} jobs, {len(machines)} machines")

    baseline = schedule(base, facility["id"], "fcfs", args.timeout)
    optimized = schedule(base, facility["id"], "cp_sat", args.timeout, time_limit_seconds=10)
    print("FCFS:", metric_summary(baseline))
    print("CP-SAT:", metric_summary(optimized))

    first = baseline["assignments"][0]
    start = as_utc(first["start_time"])
    end = max(as_utc(first["end_time"]), start + timedelta(minutes=60))
    scenario = request(
        base,
        "POST",
        "/api/v1/scenarios",
        {
            "facility_id": facility["id"],
            "name": "Smoke test machine downtime",
            "description": "Generated by scripts/smoke_api.py",
            "baseline_schedule_id": baseline["id"],
            "modifications": [
                {
                    "type": "machine_failure",
                    "machine_id": first["machine_id"],
                    "start_time": start.isoformat(),
                    "end_time": end.isoformat(),
                }
            ],
        },
    )
    assert scenario.get("id"), scenario
    posted_scenario_run = request(
        base,
        "POST",
        f"/api/v1/scenarios/{scenario['id']}/evaluate",
        {"algorithm": "fcfs", "objective": "makespan"},
    )
    altered = wait_for_run(base, "schedules", posted_scenario_run["id"], args.timeout)
    assert altered.get("assignments"), altered
    print("Downtime scenario:", metric_summary(altered))

    posted_sim = request(
        base,
        "POST",
        "/api/v1/simulations",
        {"schedule_run_id": altered["id"], "mode": "playback", "random_seed": 7},
    )
    simulation = wait_for_run(base, "simulations", posted_sim["id"], args.timeout)
    assert simulation.get("events"), "Simulation returned no event stream"
    assert simulation.get("metrics"), "Simulation returned no metrics"
    print("Simulation:", metric_summary(simulation))

    report = request(
        base,
        "POST",
        "/api/v1/reports",
        {"schedule_run_id": altered["id"], "report_type": "schedule_summary"},
    )
    assert report.get("id"), report
    for format_name in ("csv", "pdf"):
        req = Request(base.rstrip("/") + f"/api/v1/reports/{report['id']}/download?format={format_name}")
        with urlopen(req, timeout=30) as response:
            contents = response.read()
            assert response.status == 200 and len(contents) > 20
        print(f"Report {format_name.upper()}: {len(contents)} bytes")
    print("PASS: persisted demo journey")


if __name__ == "__main__":
    main()
